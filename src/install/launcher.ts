import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { launcherTarget } from "../runtime.js";
import { ensurePrivateDir, simemHome } from "../store/home.js";

export function launcherPath(): string {
  return join(simemHome(), "bin", "simem");
}

export { cliEntry } from "../runtime.js";

export function nodeSupportsSqlite(version = process.versions.node): boolean {
  const [major = 0, minor = 0] = version.split(".").map(Number);
  return major > 22 || (major === 22 && minor >= 5);
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

export function launcherScript(node: string, cli: string): string {
  if (!cli) {
    // Standalone build: the binary is the whole of simem.
    return `#!/bin/sh
# Generated by \`simem init\` (standalone simem). Hooks and the MCP server
# call this file instead of a bare \`simem\`, so desktop apps don't depend on PATH.
NODE=${shellQuote(node)}
CLI=''
if [ -x "$NODE" ]; then
  exec "$NODE" "$@"
fi
if command -v simem >/dev/null 2>&1; then
  exec simem "$@"
fi
echo "[simem] launcher target missing; run: simem init" >&2
exit 0
`;
  }
  return `#!/bin/sh
# Generated by \`simem init\`. Hooks and the MCP server call this file instead
# of a bare \`simem\`, so desktop apps don't depend on PATH (nvm, Homebrew, ...).
# Re-run \`simem init\` after upgrading simem or switching Node.js versions.
NODE=${shellQuote(node)}
CLI=${shellQuote(cli)}
if [ -x "$NODE" ] && [ -f "$CLI" ]; then
  exec "$NODE" "$CLI" "$@"
fi
# The pinned Node or simem moved (e.g. an nvm upgrade): try PATH, else stay
# silent so a host agent's hook never fails because of simem.
if command -v simem >/dev/null 2>&1; then
  exec simem "$@"
fi
echo "[simem] launcher target missing; run: simem init" >&2
exit 0
`;
}

export interface LauncherStatus {
  path: string;
  exists: boolean;
  node?: string;
  cli?: string;
  nodeOk: boolean;
  cliOk: boolean;
}

export function writeLauncher(node = launcherTarget().node, cli = launcherTarget().cli): string {
  if (!nodeSupportsSqlite()) {
    throw new Error(`simem needs Node.js >= 22.5 for its memory database; this is ${process.version}`);
  }
  const path = launcherPath();
  ensurePrivateDir(dirname(path));
  const script = launcherScript(node, cli);
  const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  if (current !== script) writeFileSync(path, script, { encoding: "utf8", mode: 0o755 });
  chmodSync(path, 0o755);
  return path;
}

export function readLauncher(): LauncherStatus {
  const path = launcherPath();
  if (!existsSync(path)) return { path, exists: false, nodeOk: false, cliOk: false };
  const script = readFileSync(path, "utf8");
  const node = /^NODE='(.*)'$/m.exec(script)?.[1];
  const cli = /^CLI='(.*)'$/m.exec(script)?.[1];
  return {
    path,
    exists: true,
    ...(node ? { node } : {}),
    ...(cli ? { cli } : {}),
    nodeOk: Boolean(node && existsSync(node)),
    // A standalone launcher has no separate CLI file.
    cliOk: cli === undefined || cli === "" ? Boolean(node && existsSync(node)) : existsSync(cli),
  };
}
