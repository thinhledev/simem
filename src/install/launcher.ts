import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ensurePrivateDir, mixaiHome } from "../store/home.js";

export function launcherPath(): string {
  return join(mixaiHome(), "bin", "mixai");
}

// The built CLI entry this install runs from (dist/cli.js), also when invoked
// from source during development.
export function cliEntry(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  const candidates = [resolve(here, "..", "cli.js"), resolve(here, "..", "..", "dist", "cli.js")];
  const found = candidates.find((path) => existsSync(path));
  if (!found) throw new Error("Could not find the built mixai CLI (dist/cli.js); run `npm run build` first");
  return found;
}

export function nodeSupportsSqlite(version = process.versions.node): boolean {
  const [major = 0, minor = 0] = version.split(".").map(Number);
  return major > 22 || (major === 22 && minor >= 5);
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

export function launcherScript(node: string, cli: string): string {
  return `#!/bin/sh
# Generated by \`mixai init\`. Hooks and the MCP server call this file instead
# of a bare \`mixai\`, so desktop apps don't depend on PATH (nvm, Homebrew, ...).
# Re-run \`mixai init\` after upgrading mixai or switching Node.js versions.
NODE=${shellQuote(node)}
CLI=${shellQuote(cli)}
if [ -x "$NODE" ] && [ -f "$CLI" ]; then
  exec "$NODE" "$CLI" "$@"
fi
# The pinned Node or mixai moved (e.g. an nvm upgrade): try PATH, else stay
# silent so a host agent's hook never fails because of mixai.
if command -v mixai >/dev/null 2>&1; then
  exec mixai "$@"
fi
echo "[mixai] launcher target missing; run: mixai init" >&2
exit 0
`;
}

export interface LauncherStatus {
  path: string;
  exists: boolean;
  node?: string;
  cli?: string;
  nodeOk: boolean;
  cliOk: boolean;
}

export function writeLauncher(node = process.execPath, cli = cliEntry()): string {
  if (!nodeSupportsSqlite()) {
    throw new Error(`mixai needs Node.js >= 22.5 for its memory database; this is ${process.version}`);
  }
  const path = launcherPath();
  ensurePrivateDir(dirname(path));
  const script = launcherScript(node, cli);
  const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  if (current !== script) writeFileSync(path, script, { encoding: "utf8", mode: 0o755 });
  chmodSync(path, 0o755);
  return path;
}

export function readLauncher(): LauncherStatus {
  const path = launcherPath();
  if (!existsSync(path)) return { path, exists: false, nodeOk: false, cliOk: false };
  const script = readFileSync(path, "utf8");
  const node = /^NODE='(.*)'$/m.exec(script)?.[1];
  const cli = /^CLI='(.*)'$/m.exec(script)?.[1];
  return {
    path,
    exists: true,
    ...(node ? { node } : {}),
    ...(cli ? { cli } : {}),
    nodeOk: Boolean(node && existsSync(node)),
    cliOk: Boolean(cli && existsSync(cli)),
  };
}
